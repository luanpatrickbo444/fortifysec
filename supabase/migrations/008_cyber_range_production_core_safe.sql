-- Rebuild verified skill totals deterministically. This is useful when an admin
-- maps a Skill to a Challenge after users have already solved that Challenge.
create or replace function public.rebuild_verified_skill_progress()
returns void
language plpgsql
security definer
set search_path=public
as $$
begin
  truncate table public.user_skill_xp;

  insert into public.user_skill_xp(user_id,skill_code,xp,updated_at)
  select
    csov.user_id,
    cskill.skill_code,
    sum(greatest(1,coalesce(ch.xp_reward,50) * cskill.weight))::integer,
    now()
  from public.challenge_solves csov
  join public.challenges ch on ch.id=csov.challenge_id
  join public.challenge_skills cskill on cskill.challenge_id=csov.challenge_id
  group by csov.user_id,cskill.skill_code;
end;
$$;
revoke all on function public.rebuild_verified_skill_progress() from public,anon,authenticated;
grant execute on function public.rebuild_verified_skill_progress() to service_role;

