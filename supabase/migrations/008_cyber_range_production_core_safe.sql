-- Raw dynamic flags are accepted only by a service-role call and are stored only as SHA-256.
create or replace function public.issue_ctf_dynamic_flag(
  p_event_id uuid,
  p_challenge_id uuid,
  p_user_id uuid,
  p_flag text,
  p_expires_at timestamptz
) returns uuid
language plpgsql
security definer
set search_path=public
as $$
declare
  v_id uuid;
begin
  if nullif(btrim(coalesce(p_flag,'')),'') is null then
    raise exception 'invalid_flag' using errcode='22023';
  end if;
  if p_expires_at is null or p_expires_at <= now() then
    raise exception 'invalid_flag_expiry' using errcode='22023';
  end if;
  if not exists(select 1 from public.ctf_events where id=p_event_id) then
    raise exception 'ctf_not_found' using errcode='22023';
  end if;
  if not exists(select 1 from public.challenges where id=p_challenge_id and published=true) then
    raise exception 'challenge_not_found' using errcode='22023';
  end if;
  if not exists(select 1 from public.ctf_participants where event_id=p_event_id and user_id=p_user_id) then
    raise exception 'participant_not_found' using errcode='22023';
  end if;

  -- Expire old unused flags for this participant/challenge.
  update public.ctf_dynamic_flags
     set expires_at = least(expires_at, now())
   where event_id=p_event_id
     and challenge_id=p_challenge_id
     and user_id=p_user_id
     and used_at is null
     and expires_at > now();

  insert into public.ctf_dynamic_flags(event_id,challenge_id,user_id,flag_hash,expires_at)
  values(p_event_id,p_challenge_id,p_user_id,digest(btrim(p_flag),'sha256'),p_expires_at)
  returning id into v_id;

  return v_id;
end;
$$;
revoke all on function public.issue_ctf_dynamic_flag(uuid,uuid,uuid,text,timestamptz) from public,anon,authenticated;
grant execute on function public.issue_ctf_dynamic_flag(uuid,uuid,uuid,text,timestamptz) to service_role;

-- Hardened CTF flag submit. Keeps the original signature so the UI does not need a rewrite.
create or replace function public.submit_ctf_flag(
  event_uuid uuid,
  challenge_uuid uuid,
  candidate_flag text
) returns boolean
language plpgsql
security definer
set search_path=public
as $$
declare
  expected bytea;
  reward integer;
  event_points integer;
  inserted_event integer;
  inserted_global integer;
  dynamic_enabled boolean;
  dynamic_flag_id uuid;
  attempt_limit integer;
  recent_attempts integer;
  is_valid boolean := false;
begin
  if auth.uid() is null or not public.has_platform_access() then return false; end if;

  select e.max_attempts_per_minute
    into attempt_limit
    from public.ctf_events e
   where e.id=event_uuid
     and e.status='live'
     and now() between e.starts_at and e.ends_at;
  if attempt_limit is null then return false; end if;

  if not exists(
    select 1 from public.ctf_participants p
     where p.event_id=event_uuid and p.user_id=auth.uid()
  ) then return false; end if;

  select count(*)::integer
    into recent_attempts
    from public.ctf_flag_attempts a
   where a.user_id=auth.uid()
     and a.event_id=event_uuid
     and a.challenge_id=challenge_uuid
     and a.attempted_at > now() - interval '1 minute';
  if recent_attempts >= coalesce(attempt_limit,10) then return false; end if;

  select c.flag_hash,c.xp_reward,c.dynamic_flag_enabled,
         coalesce(ec.points_override,c.xp_reward)
    into expected,reward,dynamic_enabled,event_points
    from public.ctf_event_challenges ec
    join public.challenges c on c.id=ec.challenge_id
   where ec.event_id=event_uuid
     and ec.challenge_id=challenge_uuid
     and c.published=true;
  if expected is null then return false; end if;

  if dynamic_enabled then
    select f.id,f.flag_hash
      into dynamic_flag_id,expected
      from public.ctf_dynamic_flags f
     where f.event_id=event_uuid
       and f.challenge_id=challenge_uuid
       and f.user_id=auth.uid()
       and f.used_at is null
       and f.expires_at > now()
     order by f.created_at desc
     limit 1;
    is_valid := dynamic_flag_id is not null
      and digest(btrim(coalesce(candidate_flag,'')),'sha256') = expected;
  else
    is_valid := digest(btrim(coalesce(candidate_flag,'')),'sha256') = expected;
  end if;

  insert into public.ctf_flag_attempts(event_id,challenge_id,user_id,success)
  values(event_uuid,challenge_uuid,auth.uid(),is_valid);

  if not is_valid then return false; end if;

  insert into public.ctf_solves(event_id,challenge_id,user_id,points)
  values(event_uuid,challenge_uuid,auth.uid(),coalesce(event_points,0))
  on conflict(event_id,challenge_id,user_id) do nothing;
  get diagnostics inserted_event = row_count;

  if inserted_event=1 then
    if dynamic_flag_id is not null then
      update public.ctf_dynamic_flags set used_at=now() where id=dynamic_flag_id and used_at is null;
    end if;

    -- Global solve/XP remains awarded only once across all contexts.
    insert into public.challenge_solves(user_id,challenge_id)
    values(auth.uid(),challenge_uuid)
    on conflict(user_id,challenge_id) do nothing;
    get diagnostics inserted_global = row_count;
    if inserted_global=1 then
      update public.profiles set xp=xp+coalesce(reward,0) where id=auth.uid();
    end if;
  end if;

  return true;
end;
$$;
revoke all on function public.submit_ctf_flag(uuid,uuid,text) from public;
grant execute on function public.submit_ctf_flag(uuid,uuid,text) to authenticated;

-- Freeze only affects what participants can see while the event is still live.
create or replace function public.get_ctf_leaderboard(event_uuid uuid, limit_count integer default 100)
returns table(user_id uuid,name text,headline text,points bigint,solves bigint,last_solve timestamptz)
language sql
stable
security definer
set search_path=public
as $$
  select p.id,p.name,p.headline,
         coalesce(sum(case
           when e.status='live' and e.freeze_at is not null and now() >= e.freeze_at and s.solved_at > e.freeze_at then 0
           else s.points end),0)::bigint as points,
         count(case
           when not (e.status='live' and e.freeze_at is not null and now() >= e.freeze_at and s.solved_at > e.freeze_at) then s.id
         end)::bigint as solves,
         max(case
           when not (e.status='live' and e.freeze_at is not null and now() >= e.freeze_at and s.solved_at > e.freeze_at) then s.solved_at
         end) as last_solve
    from public.ctf_participants cp
    join public.ctf_events e on e.id=cp.event_id
    join public.profiles p on p.id=cp.user_id and not p.blocked
    left join public.ctf_solves s on s.event_id=cp.event_id and s.user_id=cp.user_id
   where cp.event_id=event_uuid
   group by p.id,p.name,p.headline,cp.joined_at,e.status,e.freeze_at
   order by points desc, solves desc, last_solve asc nulls last, cp.joined_at asc
   limit least(greatest(limit_count,1),200);
$$;
revoke all on function public.get_ctf_leaderboard(uuid,integer) from public;
grant execute on function public.get_ctf_leaderboard(uuid,integer) to authenticated;

