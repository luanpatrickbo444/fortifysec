-- Hardened flag submit. Lab-backed dynamic challenges use:
-- FORTIFY{HMAC_SHA256(session_id:user_id:provider_lab_key)[0..31]}
-- If a provider is not configured yet, the function safely falls back to the
-- static challenge flag instead of breaking an existing CTF.
create or replace function public.submit_ctf_flag(
  event_uuid uuid,
  challenge_uuid uuid,
  candidate_flag text
) returns boolean
language plpgsql
security definer
set search_path=public
as $$
declare
  v_static_hash bytea;
  v_reward integer;
  v_event_points integer;
  v_dynamic_enabled boolean;
  v_lab_id uuid;
  v_provider_lab_key text;
  v_provider_session_id text;
  v_secret text;
  v_dynamic_flag text;
  v_attempt_limit integer;
  v_recent_attempts integer;
  v_valid boolean := false;
  v_inserted_event integer := 0;
  v_inserted_global integer := 0;
begin
  if auth.uid() is null or not public.has_platform_access() then return false; end if;

  select e.max_attempts_per_minute
    into v_attempt_limit
    from public.ctf_events e
   where e.id=event_uuid
     and e.status='live'
     and now() between e.starts_at and e.ends_at;
  if v_attempt_limit is null then return false; end if;

  if not exists(
    select 1 from public.ctf_participants p
    where p.event_id=event_uuid and p.user_id=auth.uid()
  ) then return false; end if;

  select count(*)::integer
    into v_recent_attempts
    from public.ctf_flag_attempts a
   where a.user_id=auth.uid()
     and a.event_id=event_uuid
     and a.challenge_id=challenge_uuid
     and a.attempted_at > now() - interval '1 minute';
  if v_recent_attempts >= coalesce(v_attempt_limit,10) then return false; end if;

  select c.flag_hash,
         c.xp_reward,
         c.dynamic_flag_enabled,
         c.lab_id,
         coalesce(l.provider_lab_id, l.id::text),
         coalesce(ec.points_override,c.xp_reward)
    into v_static_hash,
         v_reward,
         v_dynamic_enabled,
         v_lab_id,
         v_provider_lab_key,
         v_event_points
    from public.ctf_event_challenges ec
    join public.challenges c on c.id=ec.challenge_id
    left join public.labs l on l.id=c.lab_id
   where ec.event_id=event_uuid
     and ec.challenge_id=challenge_uuid
     and c.published=true;

  if v_static_hash is null then return false; end if;

  -- Dynamic validation only activates when the Challenge explicitly enables it
  -- AND there is a live provider-backed session. This makes rollout reversible.
  if coalesce(v_dynamic_enabled,false) and v_lab_id is not null then
    select s.provider_session_id
      into v_provider_session_id
      from public.lab_sessions s
     where s.user_id=auth.uid()
       and s.lab_id=v_lab_id
       and s.status='running'
       and s.expires_at > now()
       and nullif(s.provider_session_id,'') is not null
     order by s.started_at desc
     limit 1;

    select value into v_secret
      from public.range_private_config
     where key='dynamic_flag_secret';

    if nullif(v_provider_session_id,'') is not null
       and nullif(v_provider_lab_key,'') is not null
       and nullif(v_secret,'') is not null then
      v_dynamic_flag := 'FORTIFY{' || substr(
        encode(hmac(
          v_provider_session_id || ':' || auth.uid()::text || ':' || v_provider_lab_key,
          v_secret,
          'sha256'
        ),'hex'),
        1,32
      ) || '}';
      v_valid := digest(btrim(coalesce(candidate_flag,'')),'sha256') = digest(v_dynamic_flag,'sha256');
    else
      v_valid := digest(btrim(coalesce(candidate_flag,'')),'sha256') = v_static_hash;
    end if;
  else
    v_valid := digest(btrim(coalesce(candidate_flag,'')),'sha256') = v_static_hash;
  end if;

  insert into public.ctf_flag_attempts(event_id,challenge_id,user_id,success)
  values(event_uuid,challenge_uuid,auth.uid(),v_valid);

  if not v_valid then return false; end if;

  insert into public.ctf_solves(event_id,challenge_id,user_id,points)
  values(event_uuid,challenge_uuid,auth.uid(),coalesce(v_event_points,0))
  on conflict(event_id,challenge_id,user_id) do nothing;
  get diagnostics v_inserted_event = row_count;

  if v_inserted_event=1 then
    insert into public.challenge_solves(user_id,challenge_id)
    values(auth.uid(),challenge_uuid)
    on conflict(user_id,challenge_id) do nothing;
    get diagnostics v_inserted_global = row_count;

    if v_inserted_global=1 then
      update public.profiles
         set xp=xp+coalesce(v_reward,0)
       where id=auth.uid();
    end if;
  end if;

  return true;
end;
$$;
revoke all on function public.submit_ctf_flag(uuid,uuid,text) from public;
grant execute on function public.submit_ctf_flag(uuid,uuid,text) to authenticated;

-- Existing leaderboard RPC signature is preserved. After freeze_at, solves made
-- after the freeze remain recorded but are hidden from non-admin scoreboard views
-- until the event is finished.
create or replace function public.get_ctf_leaderboard(event_uuid uuid, limit_count integer default 100)
returns table(user_id uuid,name text,headline text,points bigint,solves bigint,last_solve timestamptz)
language sql
stable
security definer
set search_path=public
as $$
  select p.id,p.name,p.headline,
         coalesce(sum(case
           when not public.is_admin()
            and e.status='live'
            and e.freeze_at is not null
            and now() >= e.freeze_at
            and s.solved_at > e.freeze_at then 0
           else s.points end),0)::bigint as points,
         count(case
           when not (
             not public.is_admin()
             and e.status='live'
             and e.freeze_at is not null
             and now() >= e.freeze_at
             and s.solved_at > e.freeze_at
           ) then s.id end)::bigint as solves,
         max(case
           when not (
             not public.is_admin()
             and e.status='live'
             and e.freeze_at is not null
             and now() >= e.freeze_at
             and s.solved_at > e.freeze_at
           ) then s.solved_at end) as last_solve
    from public.ctf_participants cp
    join public.ctf_events e on e.id=cp.event_id
    join public.profiles p on p.id=cp.user_id and not p.blocked
    left join public.ctf_solves s on s.event_id=cp.event_id and s.user_id=cp.user_id
   where cp.event_id=event_uuid
   group by p.id,p.name,p.headline,cp.joined_at,e.status,e.freeze_at
   order by points desc, solves desc, last_solve asc nulls last, cp.joined_at asc
   limit least(greatest(limit_count,1),200);
$$;
revoke all on function public.get_ctf_leaderboard(uuid,integer) from public;
grant execute on function public.get_ctf_leaderboard(uuid,integer) to authenticated;

