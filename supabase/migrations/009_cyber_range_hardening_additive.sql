create or replace function public.award_verified_skill_progress()
returns trigger
language plpgsql
security definer
set search_path=public
as $$
declare
  v_reward integer;
  v_count integer;
begin
  select xp_reward into v_reward from public.challenges where id=new.challenge_id;

  insert into public.user_skill_xp(user_id,skill_code,xp,updated_at)
  select new.user_id,cs.skill_code,greatest(1,coalesce(v_reward,50) * cs.weight),now()
    from public.challenge_skills cs
   where cs.challenge_id=new.challenge_id
  on conflict(user_id,skill_code)
  do update set xp=public.user_skill_xp.xp+excluded.xp,updated_at=now();

  select count(*)::integer into v_count
    from public.challenge_solves where user_id=new.user_id;

  insert into public.user_badges(user_id,badge_code)
  select new.user_id,b.code from public.badges b where v_count >= b.threshold_solves
  on conflict(user_id,badge_code) do nothing;

  return new;
end;
$$;

drop trigger if exists challenge_solve_verified_progress on public.challenge_solves;
create trigger challenge_solve_verified_progress
after insert on public.challenge_solves
for each row execute procedure public.award_verified_skill_progress();

-- Rebuild skill totals from historical solves each time this migration is applied.
insert into public.user_skill_xp(user_id,skill_code,xp,updated_at)
select csov.user_id,
       cskill.skill_code,
       sum(greatest(1,coalesce(ch.xp_reward,50) * cskill.weight))::integer,
       now()
  from public.challenge_solves csov
  join public.challenges ch on ch.id=csov.challenge_id
  join public.challenge_skills cskill on cskill.challenge_id=csov.challenge_id
 group by csov.user_id,cskill.skill_code
on conflict(user_id,skill_code)
do update set xp=excluded.xp,updated_at=now();

insert into public.user_badges(user_id,badge_code)
select counts.user_id,b.code
from (
  select user_id,count(*)::integer as solves
  from public.challenge_solves
  group by user_id
) counts
join public.badges b on counts.solves >= b.threshold_solves
on conflict(user_id,badge_code) do nothing;

